export function getProgram(id: string): Program | undefined {
  return PROGRAMS.find((p) => p.id === id);
}

export function formatProgramForPrompt(p: Program): string {
  const stages = p.stages
    .map(
      (s) =>
        `  - ${s.name}｜占總成績：${s.weightPct === null ? "簡章未明列" : `${s.weightPct}%`}｜${s.method}`,
    )
    .join("\n");
  return [
    `### [${p.id}] ${p.schoolName} ${p.name}${p.code ? `（代碼 ${p.code}）` : ""}`,
    `- 招生名額：${p.quota}`,
    `- 審查／考試方式：\n${stages}`,
    `- 應繳資料：\n${p.required.map((r) => `  - ${r}`).join("\n")}`,
    `- 審查重點與偏好：\n${p.reviewFocus.map((r) => `  - ${r}`).join("\n")}`,
    p.notes.length ? `- 其他：\n${p.notes.map((r) => `  - ${r}`).join("\n")}` : "",
    `- 資料來源：${p.source}`,
  ]
    .filter(Boolean)
    .join("\n");
}
